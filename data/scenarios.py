"""训练数据的种子：关系 × 情境 × 对方当前态度。种子只用来保证覆盖面，标签仍由老师单独打。"""
import random

RELATIONSHIPS = [
    ("对方是我的伴侣", "伴侣"), ("对方是我正在暧昧的人", "暧昧对象"), ("对方是我的好朋友", "好朋友"),
    ("对方是我的普通朋友", "普通朋友"), ("对方是我的同事", "同事"), ("对方是我的上司", "上司"),
    ("对方是我的下属", "下属"), ("对方是我的客户", "客户"), ("对方是我的家人", "家人"),
    ("对方是我的前任", "前任"), ("对方是我的室友", "室友"), ("对方是我孩子的老师", "孩子的老师"),
]

SITUATIONS = [
    "对方在试探我记不记得某件事（纪念日、约定、上次说过的话）",
    "我之前做错了事，刚道歉，对方还没完全消气",
    "在约见面或开会的时间，来回商量",
    "对方在催我交东西或回复，我拖了",
    "对方向我借钱或求帮忙，我不太想答应",
    "对方冷战中，只回一两个字",
    "日常闲聊，分享吃的、照片、趣事",
    "对方抱怨工作或生活，想要安慰",
    "对方发来一条阴阳怪气的话",
    "对方在追问一件我不想细说的事",
    "对方刚给了最后通牒（再这样就分手 / 就找领导 / 就不合作了）",
    "对方分享好消息，等我的反应",
    "我拒绝了对方的请求，对方在回应",
    "对方误会了我，正在解释",
    "工作对接，确认需求和截止时间",
    "对方很久没联系，突然发消息",
    "对方问我的意见，选 A 还是选 B",
    "对方在生气，但嘴上说没事",
]

MOODS = [  # (好感度目标档位, 描述)
    (1, "对方非常生气，字里行间都是指责"),
    (2, "对方很冷淡，回得很短，明显不耐烦"),
    (3, "对方客气但有距离，没有任何热情"),
    (4, "对方就事论事，没有情绪"),
    (5, "对方友好，正常聊天，偶尔开玩笑"),
    (6, "对方很热情，主动分享，语气亲切"),
    (7, "对方很亲近，信任我，会关心我"),
    (8, "对方非常亲密，措辞里有明显的喜欢或依赖"),
]

TRENDS = ["最近几条比前面更冷", "整段情绪平稳", "最近几条比前面更热络"]
STYLES = ["微信口语，很短的句子，偶尔用表情文字如[捂脸]", "正常长度的口语", "对方话多我话少", "我话多对方话少"]


def seeds(n: int, seed: int = 0):
    rnd = random.Random(seed)
    out = []
    for i in range(n):
        rel, rel_short = rnd.choice(RELATIONSHIPS)
        mood_level, mood = rnd.choice(MOODS)
        out.append({
            "seed_id": i,
            "relationship": rel,
            "relationship_short": rel_short,
            "situation": rnd.choice(SITUATIONS),
            "mood_level": mood_level,
            "mood": mood,
            "trend": rnd.choice(TRENDS),
            "style": rnd.choice(STYLES),
            "n_messages": rnd.choice([6, 8, 8, 10, 12, 14]),
        })
    return out
